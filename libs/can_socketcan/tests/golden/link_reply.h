// A real RTM_GETLINK reply, captured from a kernel rather than written by hand.
//
// The reason for capturing rather than authoring is the same one behind
// libs/gsof's golden records: a vector written from the same reading of the
// layout as the parser agrees with the parser even where both are wrong. These
// bytes came off a Linux 7.0 kernel over its own netlink socket, from the
// pcan_usb_pro_fd driver bound to a PCAN-USB Pro FD, with:
//
//     libs/can_socketcan/tests/golden/capture.cpp can0 > reply.bin
//
// The interface was DOWN and had never been given a bit rate, which is what
// makes it worth keeping: it is the case that used to be reported as "up at
// 500 kbit/s" because nothing ever asked the kernel. Every absent field below
// is absent in the real message -- there is no IFLA_CAN_BITTIMING at all, as
// opposed to one carrying zero.
