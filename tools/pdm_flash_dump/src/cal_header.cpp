#include "pdm_flash_dump/cal_header.h"

#include <cctype>

#include <spdlog/fmt/fmt.h>

#include "pdm32/config/current_cal.h"

namespace pdm_flash_dump {

std::string current_cal_header(std::span<const uint8_t> block, std::string_view source_name, std::string_view name) {
    // Validates the header, the length and the CRC, and throws naming what is wrong.
    const pdm::config::CurrentCal cal = pdm::config::decode_current_cal(block);
    const uint16_t crc = static_cast<uint16_t>((block[pdm::config::kCurrentCalBlockBytes - 2] << 8) |
                                               block[pdm::config::kCurrentCalBlockBytes - 1]);

    std::string constant = "kCurrentCal" + std::string(name);
    if (constant.size() > 11) {
        constant[11] = static_cast<char>(std::toupper(static_cast<unsigned char>(constant[11])));
    }

    std::string out;
    out += "// The output current calibration of a real PDM32, dumped from the unit and compiled in.\n";
    out += fmt::format("// Generated by pdm_flash_dump cal-header from {}: do not edit by hand.\n", source_name);
    out += "// Per output: the calibrated count for raw ADC counts 0..31, then count = (raw * gain + offset) >> 7 "
           "above.\n";
    out += "#pragma once\n\n#include \"pdm32/config/current_cal.h\"\n\nnamespace pdm::config {\n\n";
    out += fmt::format("inline constexpr CurrentCal {} = {{\n    .outputs = {{{{\n", constant);
    for (size_t k = 0; k < cal.outputs.size(); ++k) {
        const auto& o = cal.outputs[k];
        out += fmt::format("        // O{}\n        {{.low_lut = {{", k + 1);
        for (size_t i = 0; i < o.low_lut.size(); ++i) {
            const bool last = i + 1 == o.low_lut.size();
            const bool row_end = i % 16 == 15;
            const std::string item = fmt::format("{}{}", o.low_lut[i], last ? "" : ",");
            if (last || row_end) {
                out += item;
            } else {
                out += fmt::format("{:<4}", item);
            }
            if (row_end && !last) {
                out += "\n                     ";
            }
        }
        out += fmt::format("}},\n         .gain = {},\n         .offset = {}}},\n", o.gain, o.offset);
    }
    out += "    }}};\n\n";
    out += fmt::format("// the dumped block's CRC: encode_current_cal({}) must reproduce it\n", constant);
    out += fmt::format("inline constexpr uint16_t {}Crc = 0x{:04X};\n\n", constant, crc);
    out += "}  // namespace pdm::config\n";
    return out;
}

}  // namespace pdm_flash_dump
